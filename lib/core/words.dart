/// Karşılaştırma için: küçük harf, Türkçe harfler sadeleşmiş, boşluk/nokta yerine tire.
String normalizeCode(String s) {
  const map = {'ç': 'c', 'ğ': 'g', 'ı': 'i', 'ö': 'o', 'ş': 's', 'ü': 'u', 'â': 'a', 'î': 'i', 'û': 'u'};
  final lower = s.replaceAll('İ', 'i').replaceAll('I', 'ı').toLowerCase();
  final b = StringBuffer();
  for (final ch in lower.split('')) {
    b.write(map[ch] ?? ch);
  }
  return b.toString().trim().replaceAll(RegExp(r'[\s._,/]+'), '-').replaceAll(RegExp(r'-+'), '-');
}
